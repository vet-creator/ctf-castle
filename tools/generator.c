/* Build-time generator.
 *
 * Computes  target = forward(flag)  and writes generated/mono_data.h, which
 * carries ONLY (a) the encrypted VM program and (b) the 32-byte target. The
 * clear-text flag never reaches the shipped binary -- only its image does.
 *
 * Usage:  mono_gen <output-header-path>
 * Flag inner (exactly 32 chars) is taken from $MONO_FLAG_INNER, else default.
 *
 * ---------------------------------------------------------------------------
 * DESIGNER: change DEFAULT_INNER (or set $MONO_FLAG_INNER) to your own secret,
 * and keep this file / the repo private. Distribute only monolith.exe.
 * --------------------------------------------------------------------------- */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "spn.h"
#include "vm.h"
#include "bytecode_def.h"

/* Exactly 32 printable characters. */
#define DEFAULT_INNER "th3_v01d_5t4r3s_b4ck_1nt0_y0u!!!"

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: %s <output-header>\n", argv[0]);
        return 2;
    }
    const char *inner = getenv("MONO_FLAG_INNER");
    if (!inner || !*inner) inner = DEFAULT_INNER;

    if (strlen(inner) != MONO_BLOCK) {
        fprintf(stderr,
            "error: flag inner must be exactly %d characters (got %zu)\n",
            MONO_BLOCK, strlen(inner));
        return 3;
    }

    uint8_t flag[MONO_BLOCK];
    memcpy(flag, inner, MONO_BLOCK);

    /* clear program -> tamper constant -> derived schedule */
    uint8_t plain[MONO_BC_MAX];
    size_t  bclen = mono_bc_emit(plain);
    uint32_t tamper = mono_bc_tamper_plain(plain, bclen);

    mono_ctx ctx; mono_ctx_build(&ctx, tamper);

    /* target = forward(flag) */
    uint8_t target[MONO_BLOCK];
    memcpy(target, flag, MONO_BLOCK);
    mono_forward(&ctx, target);

    /* encrypt the program for embedding */
    uint8_t enc[MONO_BC_MAX];
    memcpy(enc, plain, bclen);
    mono_bc_crypt(enc, bclen);

    /* self-check: inverse(target) must recover the flag */
    uint8_t chk[MONO_BLOCK];
    memcpy(chk, target, MONO_BLOCK);
    mono_inverse(&ctx, chk);
    if (memcmp(chk, flag, MONO_BLOCK) != 0) {
        fprintf(stderr, "internal error: forward/inverse mismatch\n");
        return 4;
    }

    FILE *f = fopen(argv[1], "w");
    if (!f) { perror("fopen"); return 5; }

    fprintf(f,
        "/* AUTO-GENERATED by mono_gen -- do not edit.\n"
        " * Contains the encrypted VM program and the target image only. */\n"
        "#ifndef MONO_DATA_H\n#define MONO_DATA_H\n#include <stdint.h>\n#include <stddef.h>\n\n");

    fprintf(f, "#define MONO_ENC_BC_LEN %zu\n", bclen);
    fprintf(f, "static const uint8_t MONO_ENC_BC[MONO_ENC_BC_LEN] = {\n");
    for (size_t i = 0; i < bclen; i++) {
        fprintf(f, "0x%02x,", enc[i]);
        if ((i % 12) == 11) fprintf(f, "\n");
    }
    fprintf(f, "\n};\n\n");

    fprintf(f, "static const uint8_t MONO_TARGET[%d] = {\n", MONO_BLOCK);
    for (int i = 0; i < MONO_BLOCK; i++) {
        fprintf(f, "0x%02x,", target[i]);
        if ((i % 12) == 11) fprintf(f, "\n");
    }
    fprintf(f, "\n};\n\n#endif\n");
    fclose(f);

    fprintf(stderr, "mono_gen: wrote %s (program %zu bytes, tamper %08x)\n",
            argv[1], bclen, tamper);
    return 0;
}
